const nums = (arr) => arr.map((n) => [String(n), String(n)]);

/** Roman numeral in a regnal name → also accept Arabic digits ("Pius XII" → "Pius 12"). */
const ROMAN = { I: 1, V: 5, X: 10, L: 50, C: 100 };
const roman = (s) => {
  let n = 0;
  for (let i = 0; i < s.length; i++) {
    const v = ROMAN[s[i]], w = ROMAN[s[i + 1]] ?? 0;
    n += v < w ? -v : v;
  }
  return n;
};
const arabic = (name) => name.replace(/\b([IVXLC]+)\b/g, (m) => String(roman(m)));
const regnal = ([pl, en, ...alt]) => [pl, en, ...alt, arabic(pl), arabic(en)];

